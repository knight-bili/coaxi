export const CodeBlock = ({
  code,
  language,
  showLineNumbers = false,
  className,
  children,
  ...props
}: CodeBlockProps) => {
  const contextValue = useMemo(() => ({ code }), [code])

  return (
    <CodeBlockContext.Provider value={contextValue}>
      <CodeBlockContainer className={className} language={language} {...props}>
        {children}
        <CodeBlockContent
          code={code}
          language={language}
          showLineNumbers={showLineNumbers}
        />
      </CodeBlockContainer>
    </CodeBlockContext.Provider>
  )
}

export type CodeBlockCopyButtonProps = ComponentProps<typeof Button> & {
  onCopy?: () => void
  onError?: (error: Error) => void
  timeout?: number
}

export const CodeBlockCopyButton = ({
  onCopy,
  onError,
  timeout = 2000,
  children,
  className,
  ...props
}: CodeBlockCopyButtonProps) => {
  const [isCopied, setIsCopied] = useState(false)
  const timeoutRef = useRef<number>(0)
  const { code } = useContext(CodeBlockContext)

  const copyToClipboard = useCallback(async () => {
    if (isCopied) return
    const ok = await copyTextToClipboard(code)
    if (!ok) {
      onError?.(new Error("Clipboard API not available"))
      return
    }
    setIsCopied(true)
    onCopy?.()
    timeoutRef.current = window.setTimeout(() => setIsCopied(false), timeout)
  }, [code, onCopy, onError, timeout, isCopied])

  useEffect(
    () => () => {
      window.clearTimeout(timeoutRef.current)
    },
    []
  )

  const Icon = isCopied ? CheckIcon : CopyIcon

  return (
    <Button
      className={cn("shrink-0", className)}
      onClick={copyToClipboard}
      size="icon"
      variant="ghost"
      {...props}
    >
      {children ?? <Icon size={14} />}
    </Button>
  )
}
// Preserve the source code-block UI; reuse Rovai's existing syntax engine.
// No shared per-code cache: equal-length interior edits cannot reuse old text.
export function CodeBlockContent({code,language,showLineNumbers=false}:{code:string;language:string;showLineNumbers?:boolean}) {
 const theme=useSyncExternalStore(subscribeSourceTheme,sourceTheme,()=>"night" as const)
 const [loaded,setLoaded]=useState<{name:string;support:LanguageSupport|null}|null>(null)
 useEffect(()=>{let current=true;void loadSourceLanguageForName(language).then(support=>{if(current)setLoaded({name:language,support})});return()=>{current=false}},[language])
 useLayoutEffect(()=>{mountSourceSyntaxHighlightStyle(theme,document)},[theme])
 const tokenized=useMemo(()=>({tokens:sourceCodeLines(code,loaded?.name===language&&loaded.support?highlightSourceCode(code,loaded.support,theme):[{text:code}]),fg:"var(--ink)",bg:"transparent"}),[code,language,loaded,theme])
 return <div className="relative overflow-auto"><CodeBlockBody showLineNumbers={showLineNumbers} tokenized={tokenized}/></div>
}
