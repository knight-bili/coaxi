const assert = require('node:assert/strict')
const { writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1000, height: 920, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  const errors = []
  window.webContents.on('console-message', event => { if (event.level === 'error' || event.level === 3) { errors.push(event.message); console.error(event.message) } })
  await window.loadFile(renderer)
  window.setContentSize(1000, 920)
  const run = code => window.webContents.executeJavaScript(code, true)
  // A hidden BrowserWindow may stop painting midway through a CSS transition.
  // Flush a frame and finish only drawer animations before inspecting rest-state
  // geometry; frame cadence/real-device touch remain outside this fixture.
  const settle = async () => {
    await run('window.viewerTest.settle()')
    await window.webContents.capturePage()
    await run('document.getAnimations().filter(a=>a.effect?.target?.matches?.(".delegation-drawer,.delegation-drawer-content")&&Number.isFinite(a.effect.getComputedTiming().endTime)).forEach(a=>a.finish())')
    return run('window.viewerTest.snapshot()')
  }
  const click = async selector => {
    const point = await run(`(() => { const node=document.querySelector(${JSON.stringify(selector)}); if (!node) throw Error('Missing '+${JSON.stringify(selector)}); node.scrollIntoView({block:'nearest'});const r=node.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)} })()`)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point })
    window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point })
    return settle()
  }
  const button = async text => { await run(`(() => { const node=[...document.querySelectorAll('button')].find(node=>node.textContent.trim()===${JSON.stringify(text)}); if (!node) throw Error('Missing button '+${JSON.stringify(text)}); node.click() })()`); return settle() }
  const escape = async () => { window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' }); window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' }); return settle() }
  const screenshots = []
  const capture = async name => {
    writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
    screenshots.push({ name, ...await run('({viewport:{width:innerWidth,height:innerHeight,pixelRatio:devicePixelRatio},bounds:viewerTest.snapshot().bounds,radius:getComputedStyle(document.querySelector(".delegation-drawer")).borderRadius})') })
    writeFileSync(join(dirname(userData), 'geometry.json'), JSON.stringify(screenshots, null, 2))
  }
  try {
    let state = await settle()
    assert.equal(state.dialogs, 0)
    state = await click('main .delegation-open')
    assert.equal(state.dialogs, 1)
    assert.ok(state.dialogTexts[0].includes('任务 1：核对自己的材料'))
    assert.ok(state.active.includes('delegation-drawer-header'), 'initial focus is a safe header, never a permission decision')
    state = await click('#parent-input')
    assert.equal(state.dialogs, 1, 'clicking the parent does not dismiss the non-modal drawer')
    assert.equal(state.active, '父会话输入', 'parent remains focusable and operable')
    await click('#outside')
    state = await escape()
    assert.equal(state.dialogs, 1, 'Escape for a sibling Radix modal must not close the drawer')
    assert.equal(await run('document.querySelectorAll("[data-state=open][role=dialog]").length'), 0)
    await run('window.viewerTest.setRows(false)'); state = await settle()
    assert.equal(state.dialogs, 1, 'unmounting launch rows cannot unmount their viewer')
    await run('window.viewerTest.setRows(true)'); await settle()
    await click('.runtime-option[data-option-id="allow-child-1"]'); state = await settle()
    assert.deepEqual(state.permissionAnswers, [{ id: 'approval-1', runId: 'run-1', version: 3, optionId: 'allow-child-1' }])
    assert.equal(await run('document.querySelectorAll(".runtime-option").length'), 0)
    await click('.native-option input[value="0"]')
    state = await button('提交回答')
    const answer = state.requests.find(row => row.method === 'runtime.interactions.resolve')
    assert.equal(answer.params.command.interactionId, 'question-child-1')
    assert.deepEqual(answer.params.command.answer.answers, [{ questionId: 'scope', labels: ['只处理 child-1 (Recommended)'] }])
    assert.ok(state.dialogTexts[0].includes('尚未确认队员收到'))
    await run('window.viewerTest.finish()'); state = await settle()
    assert.ok(state.dialogTexts[0].includes('child-1-result.txt'), 'final-body deduplication cannot hide its attachments')
    await click('.single-chat-run-history > summary'); state = await settle()
    await click('.delegation-drawer .tool-activity-group > summary'); state = await settle()
    assert.ok(state.dialogTexts[0].includes('CHILD_1_ONLY'), 'original child evidence remains reachable: ' + state.dialogTexts[0])
    await capture('viewer-day-wide')
    await run("window.viewerTest.theme('night')"); await settle(); await capture('viewer-night-wide')

    state = await click('main .delegation-card:nth-child(2) .delegation-open')
    assert.equal(state.dialogs, 1, 'one slot replaces a same-level viewer')
    assert.ok(state.dialogTexts[0].includes('帮手 2 已保存完整结果'))
    assert.ok(!state.dialogTexts[0].includes('帮手 1 已保存完整结果'))
    assert.ok(state.body[0].scrollHeight > state.body[0].height, 'long result has one useful scroll area')
    await click('main .delegation-open')
    state = await click('.delegation-drawer .delegation-open')
    assert.equal(state.dialogs, 2)
    assert.ok(state.dialogTexts.at(-1).includes('帮手 3 已保存完整结果'))
    state = await escape(); assert.equal(state.dialogs, 1, 'Escape unwinds one nested level')
    assert.ok(state.dialogTexts[0].includes('帮手 1 已保存完整结果'))
    state = await escape(); assert.equal(state.dialogs, 0)
    assert.equal(state.requests.some(row => /delegations\.(takeover|cancel|resume|message.send|conversation.end)/.test(row.method)), false, 'viewing and closing never controls execution')

    await click('main .delegation-open')
    const swipe = await run('(() => {const r=document.querySelector(".delegation-drawer-header").getBoundingClientRect();return {x:Math.round(r.left+68),y:Math.round(r.top+25),end:innerWidth-5}})()')
    window.webContents.debugger.attach('1.3')
    const touch = (type, x) => window.webContents.debugger.sendCommand('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y: swipe.y, id: 1 }] })
    await touch('touchStart', swipe.x)
    for (let step = 1; step <= 8; step++) { await touch('touchMove', Math.round(swipe.x + (swipe.end - swipe.x) * step / 8)); await new Promise(resolve => setTimeout(resolve, 16)) }
    await touch('touchEnd', swipe.end)
    window.webContents.debugger.detach()
    state = await settle(); assert.equal(state.dialogs, 0, 'original Base UI right swipe closes the drawer')

    state = await click('main .delegation-open')
    assert.equal(state.dialogs, 1, 'the original drawer can reopen after a touch swipe')
    await run('window.viewerTest.fail(true)'); state = await click('[aria-label="刷新帮手会话"]')
    assert.ok(state.dialogTexts[0].includes('会话暂时无法刷新'), JSON.stringify({ texts: state.dialogTexts, bounds: state.bounds, active: state.active, hit: await run('(() => {const r=document.querySelector("[aria-label=\\"刷新帮手会话\\"]").getBoundingClientRect();return{r:r.toJSON(),hit:document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)?.outerHTML,body:document.body.style.cssText,popup:document.querySelector(".delegation-drawer").outerHTML.slice(0,550)}})()'), requests: state.requests.slice(-6) }))
    assert.ok(state.dialogTexts[0].includes('帮手 1 已保存完整结果'))
    await run('window.viewerTest.fail(false)'); state = await button('重试')
    assert.ok(!state.dialogTexts[0].includes('会话暂时无法刷新'))
    await run('window.viewerTest.hold()'); await click('[aria-label="刷新帮手会话"]')
    await run('window.viewerTest.host(1)'); state = await settle(); assert.equal(state.dialogs, 0, 'authenticated Host change closes the old presentation')
    await run('window.viewerTest.release()'); await settle()
    state = await click('main .delegation-open')
    assert.ok(state.dialogTexts[0].includes('HOST_1'))
    assert.ok(!state.dialogTexts[0].includes('HOST_0'))
    await escape()
    await run('window.viewerTest.parent("unavailable-parent")'); await settle()
    assert.equal(await run('document.querySelectorAll("main .delegation-card").length'), 0, 'a failed new-parent list must never relabel cached old-parent rows')
    await run('window.viewerTest.parent("parent-a")'); await settle()
    for (const theme of ['day', 'night']) {
      await run(`window.viewerTest.theme(${JSON.stringify(theme)})`)
      window.setContentSize(390, 720); await settle()
      state = await click('main .delegation-card:nth-child(2) .delegation-open')
      assert.equal(state.overflowX, false)
      assert.ok(state.bounds.every(rect => rect.x >= 0 && rect.right <= 390 && rect.bottom <= 720))
      assert.ok(await run("(() => {const r=document.querySelector('[aria-label=\"关闭帮手会话\"]').getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight&&r.right<=innerWidth})()"))
      await capture(`viewer-${theme}-narrow`)
      assert.ok(await run('(() => {const b=document.querySelector(".delegation-drawer-body");b.scrollTop=b.scrollHeight;const p=[...b.querySelectorAll(".safe-markdown p")].at(-1);return b.scrollTop+b.clientHeight>=b.scrollHeight-1&&p?.textContent.includes("保留完整的会话正文")&&p.getBoundingClientRect().bottom<=b.getBoundingClientRect().bottom+1})()'), 'the complete final result remains reachable at the end of the sole scroll area')
      await escape()
    }
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ ok: true, rendererOnly: true, core: false, provider: false,
      checks: ['readonly_open_close', 'nonmodal_parent_click_and_focus', 'radix_modal_escape_shield', 'trusted_chromium_touch_swipe', 'viewer_survives_launch_row_unmount', 'exact_child_permission_and_question', 'original_execution_component', 'final_attachment_preserved', 'same_level_replacement', 'nested_escape_one_level', 'error_preserves_transcript', 'host_change_fences_late_reply', 'new_parent_error_never_relabels_cached_rows', 'day_night_wide_narrow_scroll_and_close'] }))
    app.exit(0)
  } catch (error) { console.error(error); app.exit(1) }
})
