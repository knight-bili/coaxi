const assert = require('node:assert/strict')
module.exports = async ({ window, run, settle, click, button, escape, capture }) => {
  const checks = []
  const inspect = () => run(`({value:document.querySelector('.delegation-chat-surface textarea')?.value, text:document.querySelector('.delegation-chat-surface')?.textContent, chat:viewerTest.chat.snapshot(), requests:viewerTest.snapshot().requests})`)
  const type = async text => {
    await run(`(() => {const node=document.querySelector('.delegation-chat-surface textarea');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(node,${JSON.stringify(text)});node.dispatchEvent(new Event('input',{bubbles:true}))})()`)
    await settle()
  }
  const submit = async () => { await run(`document.querySelector('.delegation-chat-surface form').requestSubmit()`); return settle() }
  await run('viewerTest.chat.start()'); await settle()
  await click('main [data-core-delegation-id] button[aria-label="查看会话"]'); await button('停止原任务并接管')
  let state = await settle()
  assert.ok(state.dialogTexts[0].includes('正在停止和清理原任务'))
  assert.equal(await run('document.querySelectorAll(".delegation-chat-surface").length'), 0)
  assert.ok(state.dialogTexts[0].includes('核对原操作'))
  await escape(); assert.equal((await settle()).dialogs, 0, 'unknown durable control may close without losing its original request')
  await click('main [data-core-delegation-id] button[aria-label="查看会话"]'); await button('核对原操作')
  state = await inspect()
  assert.equal(state.requests.filter(row => row.method === 'delegations.takeover').length, 1)
  const original = state.requests.find(row => row.method === 'delegations.takeover')
  assert.deepEqual(state.requests.find(row => row.method === 'commands.reconcile').params, { operation: original.method, params: original.params })
  checks.push('takeover_lost_reply_close_reopen_same_request_and_cleanup_gate')
  await run('viewerTest.chat.cleanup()'); await settle()
  state = await inspect()
  assert.equal(state.value, '', state.text)
  assert.equal(state.chat.storage['single-chat:thread-a']['thread-a:pending:owner-a'], 'OTHER_PARENT_DRAFT')
  assert.ok(state.text.includes('原任务：保留自己的材料与执行记录。'))
  assert.ok(state.text.includes('任务说明'))
  assert.equal(await run('document.querySelectorAll(".delegation-chat-surface .single-chat-run-history").length'), 1, 'original system task still renders its original Run')
  assert.equal(await run('document.querySelector(".single-chat-target-trigger").disabled'), true)
  assert.equal(await run('document.querySelector(".single-chat-target-trigger").textContent.includes("发起队员")'), true)
  checks.push('system_task_original_run_fixed_owner_and_foreign_pending_draft_isolation')
  await run(`(() => { const transfer=new DataTransfer();transfer.items.add(new File(['child material'],'child-only.txt',{type:'text/plain'}));const input=document.querySelector('.delegation-chat-surface input[type=file]');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true})) })()`)
  await settle(); state = await inspect()
  assert.equal(state.chat.uploads.length, 1)
  assert.equal(state.chat.uploads[0].target.kind, 'delegation_child')
  assert.ok(state.text.includes('child-only'), state.text)
  assert.equal(state.chat.coreSnapshot.draft.attachments[0].displayName, 'child-only.txt')
  checks.push('private_upload_targets_exact_child_composer')
  await type('接管后的消息和附件'); await run('viewerTest.chat.loseSend()'); await submit()
  state = await inspect()
  assert.equal(state.value, '接管后的消息和附件', 'lost receipt preserves the unsent local body until original reconciliation')
  assert.equal(await run('viewerTest.prepareLeave()'), false, 'unconfirmed send fences Thread navigation')
  await click('[aria-label="关闭帮手会话"]')
  assert.equal((await settle()).dialogs, 1, 'unconfirmed input also fences drawer close')
  await click('main [data-core-delegation-id="delegation-2"] button[aria-label="查看会话"]')
  assert.equal((await settle()).dialogs, 1)
  assert.ok((await inspect()).text.includes('原任务：'))
  await button('恢复原请求'); await settle(); state = await inspect()
  assert.equal(state.value, '')
  const sends = state.requests.filter(row => row.method === 'delegations.message.send')
  assert.equal(sends.length, 1)
  assert.equal(sends[0].params.command.threadId, undefined)
  assert.equal(sends[0].params.command.body, '接管后的消息和附件')
  assert.equal(state.chat.coreSnapshot.messages.filter(row => row.authorType === 'user').length, 1)
  assert.equal(state.chat.coreSnapshot.messages.find(row => row.authorType === 'user').attachments[0].displayName, 'child-only.txt')
  assert.ok(state.text.includes('接管后的完整回复。'))
  assert.equal(await run('viewerTest.prepareLeave()'), true, 'rollback and recovery release the original navigation guard')
  checks.push('lost_send_preserves_body_attachment_single_effect_and_leave_guards')
  await run('viewerTest.chat.queue()'); await settle()
  await click('.pending-input-edit'); await settle()
  assert.equal(await run('viewerTest.prepareLeave()'), false)
  await button('恢复原请求'); await settle(); state = await inspect()
  assert.equal(state.value, '排队消息完整移回')
  assert.equal(state.chat.coreSnapshot.draft.attachments[0].displayName, 'queued-child.txt')
  assert.equal(state.requests.filter(row => row.method === 'delegations.pendingInputs.edit').length, 1)
  assert.equal(state.chat.coreSnapshot.pendingInputs.items.length, 0)
  assert.equal(await run('viewerTest.prepareLeave()'), true)
  checks.push('pending_full_input_return_lost_receipt_recovery_and_exact_child_edit')
  await type('隐藏期间保留的草稿')
  await run(`(() => { const node=document.querySelector('.single-chat-viewport');node.scrollTop=120;node.dispatchEvent(new Event('scroll'));window.savedViewport=node;window.savedComposer=document.querySelector('.delegation-chat-surface textarea');window.savedScroll=node.scrollTop })()`)
  await button('结束'); await run('viewerTest.visible(false)'); await settle()
  assert.equal(await run('document.querySelectorAll("[role=dialog][data-state=open]").length'), 0, 'hidden child cannot leave its end modal on a different page')
  assert.equal(await run('getComputedStyle(document.querySelector(".delegation-drawer")).visibility'), 'hidden')
  await escape(); await run('viewerTest.visible(true)'); await settle()
  assert.equal(await run('document.querySelector(".delegation-chat-surface textarea")===window.savedComposer'), true)
  assert.equal((await inspect()).value, '隐藏期间保留的草稿')
  assert.equal(await run('document.querySelector(".single-chat-viewport").scrollTop'), await run('window.savedScroll'))
  await escape(); // end modal only
  assert.equal((await settle()).dialogs, 1)
  checks.push('hidden_surface_hides_modal_preserves_editor_scroll_and_draft')
  for (const theme of ['day', 'night']) {
    await run(`viewerTest.theme(${JSON.stringify(theme)})`); await settle(); await capture(`child-chat-${theme}-wide`)
  }
  window.setContentSize(390, 720); await settle()
  for (const theme of ['day', 'night']) {
    await run(`viewerTest.theme(${JSON.stringify(theme)})`); state = await settle()
    assert.equal(state.overflowX, false)
    assert.ok(state.bounds.every(rect => rect.x >= 0 && rect.right <= 390 && rect.bottom <= 720))
    assert.ok(await run(`(() => {const r=document.querySelector('.single-chat-composer').getBoundingClientRect();const b=document.querySelector('.delegation-drawer-body');return r.bottom<=innerHeight&&r.top>=0&&b.scrollHeight<=b.clientHeight+1})()`), 'composer fits without a duplicate outer scroll area')
    await capture(`child-chat-${theme}-narrow`)
  }
  checks.push('day_night_wide_narrow_embedded_layout')
  await run('viewerTest.chat.loseEnd()'); await button('结束'); await click('.danger-button'); await settle()
  state = await inspect()
  assert.equal(state.chat.coreSnapshot.conversation.status, 'ended')
  assert.ok(state.text.includes('接管后的完整回复。'), 'ending retains saved history')
  await button('核对原操作'); await settle()
  assert.equal(await run('document.querySelectorAll("[role=dialog][data-state=open]").length'), 0)
  assert.equal(await run('document.querySelector(".delegation-chat-surface textarea").disabled'), true)
  state = await inspect()
  assert.equal(state.requests.filter(row => row.method === 'delegations.conversation.end').length, 1)
  assert.equal(state.requests.some(row => row.method.startsWith('singleChat.')), false)
  checks.push('end_lost_receipt_keeps_history_disables_send_and_no_default_chat_fallback')
  return checks
}
