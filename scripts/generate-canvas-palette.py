"""Generate UI palette bindings from the fixed Codeg theme-presets source values.

Authoring only; this script does not launch an application or test rendering.
Native outputs use clipped sRGB; CSS retains the original OKLCH coordinates.
Conversion reference: https://www.w3.org/TR/css-color-4/#color-conversion-code
"""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / "integration/assets/canvas-palette.json").read_text(encoding="utf-8"))


def multiply(matrix, vector):
    return [sum(a * b for a, b in zip(row, vector)) for row in matrix]


def rgb(coordinates):
    lightness, chroma, hue = coordinates
    angle = math.radians(hue)
    lab = [lightness, chroma * math.cos(angle), chroma * math.sin(angle)]
    nonlinear = multiply([
        [1, 0.3963377773761749, 0.2158037573099136],
        [1, -0.1055613458156586, -0.0638541728258133],
        [1, -0.0894841775298119, -1.2914855480194092],
    ], lab)
    xyz = multiply([
        [1.2268798758459243, -0.5578149944602171, 0.2813910456659647],
        [-0.0405757452148008, 1.1122868032803170, -0.0717110580655164],
        [-0.0763729366746601, -0.4214933324022432, 1.5869240198367816],
    ], [value ** 3 for value in nonlinear])
    linear = multiply([
        [12831 / 3959, -329 / 214, -1974 / 3959],
        [-851781 / 878810, 1648619 / 878810, 36519 / 878810],
        [705 / 12673, -2585 / 12673, 705 / 667],
    ], xyz)
    def encode(value):
        gamma = 12.92 * value if abs(value) <= 0.0031308 else math.copysign(1.055 * abs(value) ** (1 / 2.4) - 0.055, value)
        return max(0.0, min(1.0, gamma))
    return list(map(encode, linear))


rows = [(row["id"], row["oklch"], rgb(row["oklch"])) for row in source["colors"]]
notice = "Codeg aff1e6c theme-presets.ts:78 / canvas-swatches.tsx; Apache-2.0: integration/licenses/codeg/LICENSE."
kt = "package app.codeg.android.feature.main\n\nimport androidx.compose.ui.graphics.Color\n\n// " + notice + "\n// Generated by scripts/generate-canvas-palette.py; native sRGB clipping is explicit.\nprivate val rovaiCanvasPalette=mapOf(\n"
kt += ",\n".join('    "' + key + '" to Color(' + ",".join(f"{channel:.9f}f" for channel in channels) + ")" for key, _, channels in rows)
kt += '\n)\nfun rovaiCanvasTint(value:String?):Color?=rovaiCanvasPalette[value]\n'
(ROOT / "apps/mobile-android/app/src/main/java/app/codeg/android/feature/main/RovaiCanvasPalette.kt").write_text(kt, encoding="utf-8")
swift = "import SwiftUI\n\n// " + notice + "\n// Generated by scripts/generate-canvas-palette.py; native sRGB clipping is explicit.\nprivate let rovaiCanvasPalette:[String:Color]=[\n"
swift += ",\n".join('    "' + key + '":Color(.sRGB,red:' + f"{channels[0]:.9f},green:{channels[1]:.9f},blue:{channels[2]:.9f},opacity:1)" for key, _, channels in rows)
swift += '\n]\nfunc rovaiCanvasTint(_ value:String?)->Color? {value.flatMap {rovaiCanvasPalette[$0]}}\n'
(ROOT / "apps/mobile-ios/CodegiOS/Features/Projects/RovaiCanvasPalette.swift").write_text(swift, encoding="utf-8")
css = "/* " + notice + " */\n/* Generated by scripts/generate-canvas-palette.py; original OKLCH values. */\n:root {\n"
css += "\n".join(f"  --canvas-color-{key}: oklch({' '.join(str(value) for value in oklch)});" for key, oklch, _ in rows)
css += "\n}\n"
(ROOT / "apps/desktop/src/renderer/src/canvas-palette.css").write_text(css, encoding="utf-8")
