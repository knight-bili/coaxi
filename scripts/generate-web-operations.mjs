import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// The handwritten Rust public enum is the authority. This does not inspect the
// Core dispatcher or admit private Host methods into any network interface.
const source = fileURLToPath(new URL('../crates/rovai-web/src/operations.rs', import.meta.url))
const target = fileURLToPath(new URL('../packages/contracts/src/web-operations.ts', import.meta.url))
const text = readFileSync(source, 'utf8')
const start = text.indexOf('pub enum Operation {')
const end = text.indexOf('\n}', start)
if (start < 0 || end < 0) throw new Error('Public Web Operation enum was not found')
const names = [...text.slice(start, end).matchAll(/#\[serde\(\s*rename\s*=\s*"([^"]+)"[^\]]*\)\]\s*[A-Za-z_][A-Za-z0-9_]*/g)].map(match => match[1])
if (!names.length || new Set(names).size !== names.length || names.some(name => name.startsWith('host.'))) throw new Error('Public Web operations contain invalid or duplicate names')
const content = `// Generated by scripts/generate-web-operations.mjs from the explicit Rust public enum.\n// Private Core/Host RPCs must never be added by scanning the Core dispatcher.\nexport const WEB_OPERATIONS = [\n${names.map(name => `  '${name}',`).join('\n')}\n] as const\nexport type WebOperation = typeof WEB_OPERATIONS[number]\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw new Error('Public Web operation bindings need regeneration')
} else {
  writeFileSync(target, content)
  process.stdout.write(`Wrote ${names.length} public Web operation bindings.\n`)
}
